const run = (
  id: string,
  jobId: string,
  state: BatchJob['runs'][number]['state'],
  startedAt: string,
  durationSec: number,
  processed: number,
  failed: number,
  log: BatchJob['runs'][number]['log'],
  trigger: 'schedule' | 'manual' | 'retry' = 'schedule',
) => ({
  id,
  jobId,
  state,
  startedAt,
  durationSec,
  processed,
  failed,
  trigger,
  log,
  ...(state === 'running' ? {} : { finishedAt: startedAt }),
});


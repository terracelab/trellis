/** CSV 한 칸: 쉼표 · 따옴표 · 줄바꿈이 있으면 따옴표로 감싼다 */
const cell = (v: string) => (/[",\r\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);
/** 엑셀이 저장하는 모양대로 금액은 천 단위 쉼표(따옴표로 감싼 칸) */
const money = (n: number) => (n ? formatAmount(n) : '');

/** 샘플 CSV 글자(UTF-8). 블록은 이것을 File로 만들어 실제 파일과 같은 길로 읽는다 */
export const JOURNAL_IMPORT_CSV = [
  JOURNAL_IMPORT_HEADER.join(','),
  ...ROWS.map(([no, date, code, partyId, debit, credit, memo]) =>
    [
      no,
      date,
      code,
      accountByCode(code)?.name ?? '',
      partyId ? partyById(partyId).name : '',
      money(debit),
      money(credit),
      memo,
    ]
      .map(cell)
      .join(','),
  ),
].join('\r\n');

